/* Block 4 contract: no stacked endcaps, preserved shoreline, and seeded polish. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),w={};
for(const file of ['river.js','shoreline.js','polish.js'])
 vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),{window:w},{filename:file});
const R=w.VedrasRivers,S=w.VedrasShoreline,P=w.VedrasPolish;
const cells=[];for(let q=-3;q<=3;q++)for(let r=-3;r<=3;r++)if(Math.abs(q+r)<=3)cells.push({q,r});
const sea=cells.find(c=>c.q===2&&c.r===0),wet=c=>c===sea;
const route=R.findRoute(cells,wet,{q:-2,r:0});
assert(R.valid(route,cells,wet),'real river');
const segments=R.sections(route,cells,wet),last=segments.at(-1);
const portal=R.mouthPortals([route],cells,wet,32)[0];
assert.equal(R.mouthPortals([],cells,wet).length,0);
assert.equal(portal.side,last.outSide);
const cross=R.midpoint(last,last.outSide);
assert(Math.abs(portal.x-cross.x)<1e-5&&Math.abs(portal.y-cross.y)<1e-5,'mouth uses coast EDGE midpoint');
const points=R.coursePoints(segments,route,32);
assert(Math.hypot(points.at(-2).x-cross.x,points.at(-2).y-cross.y)<1e-5,'mouth crosses midpoint');
const start=segments[0].start;
assert(Math.hypot(points[0].x-start.x,points[0].y-start.y)<1e-5,'source retains original corner');
assert(R.blocksPoint(portal.x,portal.y,[route],cells,wet,32),'real river excludes roots through coast aperture');
const coast=S.segments(cells,wet);
assert(coast.some(s=>s.cell.q===portal.landQ&&s.cell.r===portal.landR&&s.side===portal.side),'host coast exists');
assert(R.alphaAtDistance(0,32)>.95,'opaque water kernel');
assert(R.alphaAtDistance(18,32)>0&&R.alphaAtDistance(18,32)<1,'actual half-opacity bank');
assert.equal(R.alphaAtDistance(35,32),0,'terrain fully revealed beyond feather');
for(let d=0;d<40;d+=.5)assert(R.alphaAtDistance(d,32)>=R.alphaAtDistance(d+.5,32),'no hard bump in bank alpha');
const wMask=108,hMask=108,alpha=R.maskData([{x:20,y:50},{x:50,y:50},{x:80,y:50}],32,0,0,1,wMask,hMask);
const at=(x,y)=>alpha[y*wMask+x];
assert.equal(at(20,50),at(50,50),'joining vertex is not a darker/brighter semicircle');
assert.equal(at(50,50),at(80,50),'shared vertex and segment interior share one alpha');
assert(at(50,65)>0&&at(50,65)<at(50,50),'smooth bank fade');
assert.equal(at(50,85),0,'outer terrain transparent');
assert(Math.abs(at(50,65)-at(30,65))<=1,'no seam brightness at segment joints');
const once=P.patch(1337,1,-1,'shrub',1);
assert.equal(once,P.patch(1337,1,-1,'shrub',1),'stable repeatable patch');
assert(P.patch(1337,1,-1,'shrub',0)===1,'zero composition is neutral');
assert(P.patch(1337,1,-1,'shrub',1)>=.6&&P.patch(1337,1,-1,'shrub',1)<=1.4);
const offset=P.localOffset(1337,1,-1,'shrub',7,1,1);
assert.deepEqual(JSON.parse(JSON.stringify(offset)),JSON.parse(JSON.stringify(P.localOffset(1337,1,-1,'shrub',7,1,1))));
assert.notDeepEqual(JSON.parse(JSON.stringify(offset)),JSON.parse(JSON.stringify(P.localOffset(1337,1,-1,'shrub',7,1,0))),
 'grouping intensity actually shifts candidate positions');
const origin=[117,166,91];
assert.deepEqual(JSON.parse(JSON.stringify(P.terrainRGB(...origin,0,'ground','grassland'))),origin,'zero tone is reversible');
assert.deepEqual(JSON.parse(JSON.stringify(P.terrainRGB(...origin,1,'water','ocean'))),origin,'water remains ungraded');
assert.deepEqual(JSON.parse(JSON.stringify(P.terrainRGB(...origin,1,'ground','snowfields'))),origin,'snow untouched');
assert.notDeepEqual(JSON.parse(JSON.stringify(P.terrainRGB(...origin,1,'ground','grassland'))),origin,'ground texture quieted');
assert.equal(P.natureFilter({kind:'tree',family:'oaks'},0),'none','off means raw artwork');
assert.equal(P.natureFilter({kind:'mountain'},1),'none','mountain artwork unchanged');
const saved=P.valid({nature:90,terrain:-2,composition:.65});
assert.equal(saved.nature,1);assert.equal(saved.terrain,0);assert.equal(saved.composition,.65);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const editor=fs.readFileSync(path.join(root,'nature-ui.js'),'utf8');
const auto=fs.readFileSync(path.join(root,'autotile.js'),'utf8');
const shoreline=fs.readFileSync(path.join(root,'shoreline.js'),'utf8');
for(const id of ['polishNature','polishTerrain','polishComposition'])assert(html.includes('id="'+id+'"'),'visual control missing '+id);
assert(html.indexOf('polish.js?v=0.21.0')<html.indexOf('app.js?v=0.31.0'),'polish module loads before the map');
assert(html.includes('river.js?v=0.28.0')&&html.includes('shoreline.js?v=0.29.0'));
assert(app.includes('mouthPortals=state.river?')&&app.includes('mouthPortals,version:4'),'coast uses mouth apertures');
assert(!app.includes('skipEdges'),'old whole-coast suppression gone');
assert(shoreline.includes('const allSegments=options.segments||segments(cells,isWet)'),'keep all real coastline segments');
assert(shoreline.includes('dst[alphaIndex]=Math.round(dst[alphaIndex]*(1-passage))'),'narrow coast portal feathering');
assert(app.includes('visualPolish:state.visualPolish'),'scene export stores polish');
assert(app.includes('state.visualPolish=window.VedrasPolish.valid(scene.visualPolish)'),'scene import restores polish');
assert(app.includes('terrainRasterCache.signature=null'),'terrain-tone slider invalidates raster');
assert(app.includes('window.VedrasPolish.natureFilter'),'renderer-toned Nature sprites');
assert(auto.includes('terrainTone([red,green,blue]'),'terrain gets non-destructive tone');
assert(editor.includes('window.VedrasPolish.localOffset')&&editor.includes('window.VedrasPolish.patch'),'plants use patches');
console.log('PASS Block 4: joined feather mask without half-circle stacking, intact coast aperture, spatial vegetation, reversible palette and persistence.');
