/* Regression: forest is an independent, deterministic overlay, not another terrain PNG. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),window={};
vm.runInNewContext(fs.readFileSync(path.join(root,'forest.js'),'utf8'),{window},{filename:'forest.js'});
const F=window.VedrasForest;
const catalog=JSON.parse(fs.readFileSync(path.join(root,'assets/terrain/terrain_catalog.json'),'utf8'));
const cells=[];
for(let r=-3;r<=3;r++)for(let q=-3;q<=3;q++)if(Math.abs(q+r)<=3)
 cells.push({q,r,terrainTypeId:'grassland',biome:'plains'});
const get=(config,cellsToUse=cells)=>F.generate(cellsToUse,catalog,config,c=>c.terrainTypeId);
const d=F.defaults();
assert.deepEqual(JSON.parse(JSON.stringify(get(d))),JSON.parse(JSON.stringify(get(d))),'same seed must give identical forest');
const before=get(d);
assert.equal(before.length,37);
assert(before.some(c=>c.forestClass==='dense_forest'),'at least one dense woodland patch');
assert(before.some(c=>c.forestClass==='light_forest'),'light woodland must exist');
assert(before.some(c=>c.forestClass==='none'&&c.edgeInfluence>0),'forest edge spillover must exist');
assert(before.filter(c=>c.density>0).length>before.filter(c=>c.baseDensity>0).length,'spillover extends beyond core forest');
assert(before.every(c=>c.suitability>0&&c.density>=0&&c.density<=1));
assert.notDeepEqual(JSON.parse(JSON.stringify(get({...d,seed:987654}))),JSON.parse(JSON.stringify(before)),'changing seed must change forest');
assert(get({...d,enabled:false}).every(c=>c.density===0));
assert(get({...d,coverage:0}).every(c=>c.density===0),'no automatic forest when coverage is zero');
const forced=get({...d,enabled:true,coverage:0,overrides:{'0,0':'dense_forest','1,0':'light_forest'}});
assert.equal(forced.find(c=>c.key==='0,0').forestClass,'dense_forest');
assert.equal(forced.find(c=>c.key==='1,0').forestClass,'light_forest');
assert(forced.some(c=>c.forestClass==='none'&&c.edgeInfluence>0),'manual woodland produces a fringe');
const clear=get({...d,overrides:{'0,0':'none'}});
assert.equal(clear.find(c=>c.key==='0,0').density,0,'manual clear has priority over neighbors');
const noEdge=get({...d,coverage:0,edgeStrength:0,overrides:{'0,0':'dense_forest'}});
assert(noEdge.every(c=>c.key==='0,0'||c.edgeInfluence===0),'edge slider can eliminate spillover');
const mix=cells.map(c=>({...c}));
mix.find(c=>c.q===0&&c.r===0).terrainTypeId='ocean';
mix.find(c=>c.q===1&&c.r===0).terrainTypeId='jungle';
mix.find(c=>c.q===-1&&c.r===0).terrainTypeId='snowfields';
const jung=get({...d,jungleHexes:{'0,0':true,'1,0':true}},mix);
assert.equal(jung.find(c=>c.key==='0,0').density,0,'ocean blocks jungle/forest override');
assert.equal(jung.find(c=>c.key==='0,0').jungle,false);
assert.equal(jung.find(c=>c.key==='1,0').jungle,true);
assert.equal(jung.find(c=>c.key==='1,0').forestClass,'dense_forest');
assert.equal(jung.find(c=>c.key==='1,0').biome,'jungle','independent jungle biome');
assert(jung.find(c=>c.key==='-1,0').suitability>0,'cold conifers may grow');
assert.equal(F.preferredFamily('savanna_trees',jung.find(c=>c.key==='1,0')),false);
assert.equal(F.preferredFamily('palms',jung.find(c=>c.key==='1,0')),true);
assert.equal(F.treeTarget(jung.find(c=>c.key==='1,0')),5);
const safe=F.valid({enabled:true,coverage:55,edgeStrength:-2,overrides:{'0,0':'light_forest','1,1':'BAD','../../etc':'dense_forest'},jungleHexes:{'1,0':true,'1,1':'yes'}});
assert.equal(safe.coverage,1);assert.equal(safe.edgeStrength,0);
assert.equal(safe.overrides['0,0'],'light_forest');assert.equal(Object.keys(safe.overrides).length,1);
assert.equal(safe.jungleHexes['1,0'],true);assert.equal(Object.keys(safe.jungleHexes).length,1);
console.log('PASS: deterministic clustered forests, light/dense forest, neighboring falloff, jungle biome, water protection, per-hex override and seed reproducibility.');
