/* FloraV2 merged into main as a supplemental read-only registry. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),ctx={window:{}};vm.createContext(ctx);
for(const script of ['flora-plan.js','terrain-plan.js','nature_catalog.js','existing-asset-rules.js']){
 vm.runInContext(fs.readFileSync(path.join(root,script),'utf8'),ctx,{filename:script});
}
const F=JSON.parse(fs.readFileSync(path.join(root,'plans/flora_v2_registry.json'),'utf8'));
const T=JSON.parse(fs.readFileSync(path.join(root,'plans/terrain_catalog_seed.json'),'utf8'));
const N=JSON.parse(fs.readFileSync(path.join(root,'assets/nature/nature_catalog.json'),'utf8'));
const R=JSON.parse(fs.readFileSync(path.join(root,'assets/terrain/terrain_catalog.json'),'utf8'));
const P=JSON.parse(fs.readFileSync(path.join(root,'plans/sprite_catalog_plan.json'),'utf8'));
assert.equal(F.species.length,104);
assert.equal(P.items.length,17);
assert.equal(F.species.reduce((n,s)=>n+s.aliases.length,0),148);
assert.equal(new Set(F.species.flatMap(s=>s.aliases)).size,148);
const known=new Set(Object.keys(N.entries).map(x=>path.basename(x)));
assert.equal(known.size,148);
for(const a of F.species.flatMap(s=>s.aliases))assert(known.has(a),'unexpected FloraV2 alias '+a);
const kapok=F.species.find(s=>s.id==='jungle_tree_01');
assert.equal(kapok.name,'Kapokbaum');assert.equal(kapok.family,'jungle_trees');
assert.deepEqual(kapok.allowedTerrainTypes,['jungle']);
for(let i=12;i<=19;i++)assert.equal(N.entries['nature/tree_'+i+'.png'].id,'kapok_tree_'+i);
assert.deepEqual(F.species.find(s=>s.id==='snow_pine_01').aliases,Array.from({length:5},(_,i)=>'tanne_schnee_0'+(i+1)+'.png'));
assert.deepEqual(F.species.find(s=>s.id==='snow_fir_01').aliases,Array.from({length:5},(_,i)=>'tanne_schnee_'+String(i+6).padStart(2,'0')+'.png'));
assert.equal(F.species.find(s=>s.id==='fir_01').aliases.length,11);
assert.notEqual(T.terrainTypes.find(t=>t.id==='jungle').archived,true);
assert.equal(Object.keys(T.assets).length,104);
assert.equal(Object.keys(R.assets).length,104);
assert.equal(ctx.window.VedrasFloraPlan.species.length,104);
assert.notEqual(ctx.window.VedrasTerrainPlan.terrainTypes.find(t=>t.id==='jungle').archived,true);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(html.includes('id="floraV2Panel"'));
assert(html.includes('flora-workspace.js?v=0.13.0'));
const workspace=fs.readFileSync(path.join(root,'flora-workspace.js'),'utf8');
assert(!workspace.includes('stopImmediatePropagation'));
assert(!workspace.includes('natureInstances='));
assert(!workspace.includes('forestBaseBiomeByHex'));
assert(!workspace.includes('hexTerrain['));
console.log('FloraV2 OK: 104 reference categories, 148 original filenames, 25 terrain sources, current Kapok and forest preserved.');
