'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const js=fs.readFileSync(path.join(root,'world-tile-streamer.js'),'utf8');
const ctx={window:{}};vm.runInNewContext(js,ctx);
const crop=ctx.window.VedrasWorldTiles.coreSourceCrop;
test('native 4x ground crop avoids both transparent gutter edges',()=>{
 const img={width:2072,height:1761};
 const out=crop(img,3,512);
 assert.equal(out.x,13);
 assert.ok(Math.abs(out.y-1761*3/518-1)<1e-9);
 assert.ok(out.w>2040&&out.w<2048);
 assert.ok(out.h>1730&&out.h<1740);
 const lastX=out.x+out.w;
 assert.ok(lastX<img.width-img.width*3/518);
 assert.equal(crop(img,0,512),null);
 const small=crop({width:8,height:8},3,512);
 assert.ok(small.w>0&&small.h>0);
});
test('scenery projection unchanged and core destination remains device-snapped',()=>{
 assert(js.includes('const source=core?coreSourceCrop(asset.image,pad,obj.t.size):null;'));
 assert(js.includes('const snap=x=>Math.round(x*view.dpr)/view.dpr;'));
 assert(js.includes("layerPass(['ground','terrain'],0);"));
 assert(!js.includes('const ratio=pad?pad/(obj.t.size+pad*2):0;'));
 assert(js.includes('if(core)area=drawImage(asset.image,obj.dx,obj.dy,obj.dw,obj.dh,'));
 assert(js.includes('if(asset.crop){'),'sprite source cropping remains separate');
 const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
 assert(html.includes('world-tile-streamer.js?v=0.22.6'));
});
